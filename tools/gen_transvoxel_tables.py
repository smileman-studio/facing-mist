def block(name, txt):
    idx = txt.index(name)
    brace = txt.index("{", idx)
    depth = 0
    i = brace
    while i < len(txt):
        if txt[i] == "{":
            depth += 1
        elif txt[i] == "}":
            depth -= 1
            if depth == 0:
                break
        i += 1
    return txt[brace + 1:i]

def hexlist(s):
    out = []
    for x in s.split(","):
        x = x.strip()
        if x:
            out.append(int(x, 16 if x.lower().startswith("0x") else 10))
    return out

def parse_cell(body):
    ent = re.findall(r"GeometryCounts\s*=\s*(0x[0-9A-Fa-f]+)\s*,\s*VertexIndex\s*=\s*new\s+byte\[\]\s*\{([^}]*)\}", body)
    return [(int(c, 16), hexlist(ix)) for c, ix in ent]

def parse_rows(body):
    return [hexlist(r) for r in re.findall(r"new\s+ushort\[\]\s*\{([^}]*)\}", body)]

