namespace SmilemanStudio.Core
{
    /// <summary>
    /// Уровень (тир) симуляции острова (ADR 0001).
    /// Определяет, насколько подробно остров обрабатывается симуляцией.
    /// </summary>
    public enum IslandTier
    {
        /// <summary>
        /// Тир не задан (значение по умолчанию). Не является валидным состоянием острова.
        /// </summary>
        None = 0,

        /// <summary>
        /// Игрок находится на острове — полная ECS-симуляция.
        /// </summary>
        Hot = 1,

        /// <summary>
        /// Игрок на соседнем острове — упрощённая ECS-симуляция.
        /// </summary>
        Warm = 2,

        /// <summary>
        /// Игрок далеко, но остров в поле зрения или зоне интереса —
        /// симуляция только через макро-модель (<c>IslandTierState</c>), без внутренних сущностей.
        /// </summary>
        Cold = 3,

        /// <summary>
        /// Игрок никогда не был на острове, но он существует в мире —
        /// базовая симуляция жизни фракций и захвата через <c>IslandTierState</c>,
        /// без внутренних сущностей.
        /// </summary>
        Background = 4
    }
}
