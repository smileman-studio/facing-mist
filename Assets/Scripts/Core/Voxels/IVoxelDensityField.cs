using Unity.Mathematics;

namespace SmilemanStudio.Core.Voxels
{
    /// <summary>
    /// Контракт поля плотности воксельного движка (ADR-0002, D4/D7).
    /// </summary>
    /// <remarks>
    /// Воксельный движок оперирует ТОЛЬКО этим контрактом: ему безразлично, откуда
    /// берётся форма — из SDF острова, из аналитической сферы или из загруженного
    /// тома. Реализация обязана быть чистой функцией точки и возвращать плотность в
    /// единой системе значений.
    ///
    /// Единицы: вход <paramref name="voxel"/> — координата в вокселях LOD0 (шаг 0,5 м,
    /// ADR-0002 D8), вне зависимости от мешируемого LOD. Выход — <c>short</c> плотности
    /// в единицах <see cref="VoxelConstants.DensityUnitsPerVoxel"/> на шаг сетки LOD0
    /// (256 единиц = один воксель LOD0). Знак: d &lt;= 0 — грунт, d &gt; 0 — воздух.
    ///
    /// Контракт скалярный (одна точка): пакетная выборка кэша — работа
    /// <see cref="VoxelFieldSampler"/>, а не реализации поля.
    ///
    /// Детерминизм (ADR-0002 D6): реализация обязана быть детерминированной функцией
    /// точки. Любые трансцендентные и платформенно-зависимые операции запрещены, если
    /// результат влияет на занятость.
    /// </remarks>
    public interface IVoxelDensityField
    {
        /// <summary>
        /// Плотность в вокселе LOD0.
        /// </summary>
        /// <param name="voxel">Island-local/world воксель LOD0 (шаг 0,5 м).</param>
        /// <returns><c>short</c> плотности: 256 единиц на воксель LOD0, d&lt;=0 — грунт.</returns>
        short SampleDensity(int3 voxel);
    }
}
